// Bundles the whole server into a single ESM file with no node_modules runtime
// dependency, so the release folder is fully self-contained (Node + the folder).
import { build } from 'esbuild';
import { rmSync, mkdirSync } from 'node:fs';

rmSync('bundle', { recursive: true, force: true });
mkdirSync('bundle', { recursive: true });

await build({
  entryPoints: ['src/server.ts'],
  outfile: 'bundle/server.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'none',
  banner: {
    js:
      '// dota2-mcp — bundled MCP server (Dota 2 Source 2 asset introspection).\n' +
      '// Generated by scripts/bundle.mjs; do not edit by hand.\n' +
      "import { createRequire as __cr } from 'node:module';\n" +
      'const require = __cr(import.meta.url);\n',
  },
  logLevel: 'info',
});

console.log('bundled -> bundle/server.mjs');
